"""
rag/memory.py — Conversation Summary Memory Manager

Implements a two-layer memory system:
    Layer 1 — Summary:       compressed text of all turns older than the
                             recency window, generated by the LLM itself.
    Layer 2 — Recent turns:  the last RECENT_TURNS_KEEP turns kept verbatim.

The prompt builder receives both layers and assembles them in order:
    [system] [context] [summary] [recent turns] [query]

This keeps the prompt lean regardless of conversation length while
preserving the full arc of the conversation in the summary.
"""

import config
import database


# ── Summary prompt ────────────────────────────────────────────────────────────

SUMMARIZER_PROMPT_TEMPLATE = """You are a conversation summarizer.
Below is a conversation between a user and an AI assistant about documents
in a knowledge base. Summarize this conversation concisely.

Rules:
- Keep the summary under {max_chars} characters.
- Preserve key facts, questions asked, and answers given.
- Write in third person: "The user asked about X. The assistant explained Y."
- Do NOT add any information not present in the conversation.
- Do NOT include greetings or filler phrases.

Conversation to summarize:
{conversation}

Summary:"""


def _format_conversation_for_summary(messages: list[dict]) -> str:
    """
    Format a list of message dicts into a readable conversation transcript
    suitable for the summarizer prompt.

    Args:
        messages: List of {"role": str, "content": str} dicts.

    Returns:
        A formatted string with role labels and message content.
    """
    lines = []
    for msg in messages:
        role = "User" if msg["role"] == "user" else "Assistant"
        lines.append(f"{role}: {msg['content']}")
    return "\n\n".join(lines)


def _call_llm_for_summary(prompt: str, llm) -> str:
    """
    Call the LLM synchronously to generate a summary string.

    Uses llm.generate() (non-streaming) since we need the complete
    summary text before building the prompt — we can't yield tokens here.

    Args:
        prompt: The full summarizer prompt string.
        llm:    Any BaseLLM instance (OllamaLLM or future providers).

    Returns:
        The generated summary string, stripped of leading/trailing whitespace.
        Returns an empty string if generation fails — callers handle this
        gracefully by falling back to raw history.
    """
    try:
        summary = llm.generate(prompt)
        return summary.strip()
    except Exception as e:
        print(f"[memory] Summary generation failed: {e}")
        return ""


# ── Core memory manager ───────────────────────────────────────────────────────

class ConversationMemory:
    """
    Manages the two-layer memory for a single session.

    Usage in process_query_stream:
        memory  = ConversationMemory(session_id, llm)
        context = memory.get_memory_context()
        prompt  = build_prompt(chunks, context["recent"], query,
                               summary=context["summary"])
    """

    def __init__(self, session_id: str, llm):
        """
        Args:
            session_id: The active chat session UUID.
            llm:        Any BaseLLM instance. Used for summary generation.
        """
        self.session_id = session_id
        self.llm        = llm

    def _count_turns(self) -> int:
        """
        Count the number of complete turns (user+assistant pairs) in this session.
        A turn = 1 user message + 1 assistant message = 2 rows in messages.
        """
        history = database.get_history(self.session_id, limit=10000)
        return len(history) // 2

    def _needs_summarization(self) -> bool:
        """
        Return True if the session is long enough to warrant summarization.

        Summarization kicks in when:
            total_turns > SUMMARY_THRESHOLD

        Below the threshold we send full raw history — cheap and accurate.
        Above it we compress old turns into a summary.
        """
        return self._count_turns() > config.SUMMARY_THRESHOLD

    def _get_split_point(self, all_messages: list[dict]) -> int:
        """
        Calculate the index that divides "old history to summarize" from
        "recent turns to keep verbatim".

        We keep the last RECENT_TURNS_KEEP turns (each turn = 2 messages)
        verbatim. Everything before that split point goes into the summary.

        Args:
            all_messages: Full message list ordered oldest-first.

        Returns:
            Integer index. Messages[:split] → summary input.
            Messages[split:] → verbatim recent window.
        """
        recent_messages_count = config.RECENT_TURNS_KEEP * 2
        split = max(0, len(all_messages) - recent_messages_count)
        return split

    def _should_update_summary(
        self,
        existing_summary: dict | None,
        all_messages: list[dict],
    ) -> bool:
        """
        Decide whether the existing summary needs to be regenerated.

        The summary is stale when new messages have been added beyond
        what was covered by the last summary. Specifically, if the
        highest message ID in the "old" portion exceeds the stored
        summarized_up_to_id, regeneration is needed.

        Args:
            existing_summary: The current summary row from SQLite, or None.
            all_messages:     Full message list with id fields.

        Returns:
            True if summary should be regenerated, False if current is fresh.
        """
        if existing_summary is None:
            return True

        split           = self._get_split_point(all_messages)
        old_messages    = all_messages[:split]

        if not old_messages:
            return False

        # The highest ID we'd include in the summary right now
        highest_id = max(m["id"] for m in old_messages if "id" in m)

        # If higher than what was last summarized — summary is stale
        return highest_id > existing_summary["summarized_up_to_id"]

    def get_memory_context(self) -> dict:
        """
        Build the two-layer memory context for the current prompt.

        Decision tree:
            Short session (turns ≤ SUMMARY_THRESHOLD):
                → return full history as "recent", empty summary
            Long session, fresh summary:
                → return existing summary + recent verbatim turns
            Long session, stale summary:
                → regenerate summary from old turns
                → save to SQLite
                → return new summary + recent verbatim turns

        Returns:
            Dict with two keys:
                "summary" (str):        Compressed summary of old turns.
                                        Empty string if not applicable.
                "recent"  (list[dict]): Recent turns kept verbatim.
                                        Format: [{"role": ..., "content": ...}]
        """
        # Fetch the complete message history with IDs for split calculation
        with database.get_connection() as conn:
            rows = conn.execute(
                "SELECT id, role, content FROM messages "
                "WHERE session_id = ? ORDER BY timestamp ASC",
                (self.session_id,),
            ).fetchall()
        all_messages = [
            {"id": r["id"], "role": r["role"], "content": r["content"]}
            for r in rows
        ]

        # Short session — no summarization needed yet
        if not self._needs_summarization():
            recent = [{"role": m["role"], "content": m["content"]}
                      for m in all_messages]
            print(
                f"[memory] Session short ({len(all_messages)} msgs) "
                "— sending full history."
            )
            return {"summary": "", "recent": recent}

        split        = self._get_split_point(all_messages)
        old_messages = all_messages[:split]
        new_messages = all_messages[split:]

        recent = [{"role": m["role"], "content": m["content"]}
                  for m in new_messages]

        # Check if we have a usable existing summary
        existing = database.get_summary(self.session_id)

        if not self._should_update_summary(existing, all_messages):
            # Existing summary is fresh — use it
            print(
                f"[memory] Using cached summary "
                f"(covers up to msg id {existing['summarized_up_to_id']})."
            )
            summary_text = existing["summary"][:config.SUMMARY_MAX_CHARS]
            return {"summary": summary_text, "recent": recent}

        # Summary is stale or missing — regenerate
        print(
            f"[memory] Generating summary for "
            f"{len(old_messages)} old messages..."
        )

        if not old_messages:
            return {"summary": "", "recent": recent}

        conversation_text = _format_conversation_for_summary(old_messages)
        summarizer_prompt = SUMMARIZER_PROMPT_TEMPLATE.format(
            max_chars=config.SUMMARY_MAX_CHARS,
            conversation=conversation_text,
        )

        summary_text = _call_llm_for_summary(summarizer_prompt, self.llm)

        if summary_text:
            # Persist so we don't regenerate on every turn
            highest_id = max(m["id"] for m in old_messages)
            database.save_summary(self.session_id, summary_text, highest_id)
            print(
                f"[memory] Summary saved "
                f"(up to msg id {highest_id}, "
                f"{len(summary_text)} chars)."
            )
        else:
            # LLM failed to generate — fall back to raw old history
            print("[memory] Summary generation failed — using raw old history.")
            raw_old = [{"role": m["role"], "content": m["content"]}
                       for m in old_messages]
            return {"summary": "", "recent": raw_old + recent}

        return {
            "summary": summary_text[:config.SUMMARY_MAX_CHARS],
            "recent":  recent,
        }
    